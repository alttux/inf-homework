# Инвертирование битов — замена 0 на 1 и наоборот

for n in range(0, 256):
    nb = bin(n)[2:]
    # Инвертируем через замену символов через промежуточный символ
    nb = nb.replace('0', '*')
    nb = nb.replace('1', '0')
    nb = nb.replace('*', '1')

    nbt = str(int(nb, 2))
    r = int(nbt[::-1])  # разворот строки — реверс цифр числа
    if r == 97:
        print(n)
