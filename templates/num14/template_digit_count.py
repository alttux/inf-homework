# Задание 14: подсчёт цифр в двоичной/шестнадцатеричной записи числа
# Типичные варианты: count('1'), count('0'), count('7') и т.д.

# Считаем единицы в двоичной записи
s = 16**16 + 8**8 + 32**4
print(bin(s)[2:].count('1'))  # bin() добавляет '0b' — срезаем его

# Считаем '7' в восьмеричной записи
s2 = 4096**8 + 512**64 - 64**512
print(oct(s2).count('7'))  # oct() добавляет '0o'

# Считаем через hex() — букву 'b' в шестнадцатеричной
s3 = 64**123 + 57**371 - 23**63
print(bin(hex(s3)[2:].count('b'))[2:])
