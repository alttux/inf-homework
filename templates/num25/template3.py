from fnmatch import fnmatch

# Задание 25: поиск через fnmatch — удобнее для сложных масок
# Маска: 123*578 (начинается на 123, заканчивается на 578, в середине что угодно)

for x in range(31, 10**8, 31):
    if str(x)[:3] == '123' and str(x)[-3:] == '578':
        print(f'{x} | {x // 31}')

print('---')

# Альтернатива: fnmatch — glob-стиль (* — любое количество символов)
for i in range(31, 10**8, 31):
    if fnmatch(str(i), '123*578'):
        print(i, i // 31)
