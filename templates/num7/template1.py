from math import ceil, log2

# Задание 7: объём видеофайла при заданном разрешении и количестве цветов
# Формула: V = h * w * i * k / скорость_передачи
# i = ceil(log2(n)) — количество бит на пиксель при n цветах

hw = 1920 * 1920  # разрешение (пиксели = h * w)
n = 16_384         # количество цветов
i = ceil(log2(n)) # бит на пиксель
v = 1_474_560      # скорость передачи (бит/с)

# Перебираем количество кадров k, пока объём не превысит лимит
for k in range(1, 1000):
    t = (hw * i * k) / v  # время передачи в секундах
    if t <= 280:
        print(k)
