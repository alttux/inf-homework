from math import ceil, log2

# Задание 7: найти максимальное количество цветов (2^i) при заданном объёме

h = 1024
w = 1024
k = 32    # количество кадров
v = 1_474_560  # скорость передачи

# Перебираем количество бит на пиксель i
for i in range(1, 1000):
    t = (h * w * i * k) / v
    if t <= 120:
        # 2^i — количество цветов, соответствующее i битам
        print(2 ** i)
