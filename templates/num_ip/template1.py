from ipaddress import *

# Задание: подсчёт IP-адресов в сети, удовлетворяющих условию
# Условие: количество единиц в двоичной записи делится на 2

net = ip_network("192.168.32.160/255.255.255.240", 0)
c = 0

for ip in net:
    # f'{ip:b}' — двоичная запись IP-адреса (без префикса 0b)
    if f"{ip:b}".count('1') % 2 == 0:
        c += 1

print(c)
