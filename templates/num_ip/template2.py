from ipaddress import *

# Задание: подсчёт IP, у которых единиц в старших 16 битах >= единиц в младших 16 битах
# Дополнительная сложность: условие на части адреса (октеты)

net = ip_network("142.96.56.118/255.255.255.240", 0)
c = 0

for ip in net:
    b = f"{ip:b}"
    # Делим 32-битный адрес пополам: старшие 16 бит — b[:16], младшие — b[16:]
    if b[16:].count('1') > b[:16].count('1'):
        c += 1

print(c)
