from ipaddress import *

# Задание: перебор маски (третий октет — степени двойки 1..9)
# Найти первую маску, при которой выполняется условие

for n in range(0, 9):
    # Формируем байт маски: n единиц, потом нули (до 8 бит)
    A = int('1' * n + '0' * (8 - n), 2)
    net = ip_network(f'255.201.33.160/255.255.{A}.0', 0)
    # all() — условие верно для каждого адреса сети
    if all(f'{ip:b}'[:16].count('1') >= f'{ip:b}'[16:].count('1') for ip in net):
        print(A)
        break
