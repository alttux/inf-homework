f = open('task.txt')

# Задание 13 / работа с файлом: map() для построчного применения функции
# Каждая строка — набор чисел; вычисляем квадрат каждого и суммируем

def sqr(x):
    return int(x) ** 2


for line in f:
    # map(функция, итерируемое) — применяет функцию к каждому элементу
    print(sum(list(map(sqr, line.split()))))
