f = open('6.txt')
c = 0
for i, l  in enumerate(f, 1): # enumerate для узнавания номера строки
    s = list(map(int, l.split()))
    # print(s, i)
    np = [x for x in s if s.count(x) == 1] # неповторяющиеся числа
    p = [x for x in s if s.count(x) > 1] # повторяющиеся числа
    u1 = i%3 == 0 # условие первое
    u2 = len(set(p))*2 < len(s) # условие второе
    if len(np) != 0: # 1 случай когда есть неповторяющиеся числа
        if u1 + u2 + (max(np)**2 > sum(set(p))**2) == 2: # сумма сразу всех условий сразу
            c+=1
    else: # 2 случай когда нет неповторяющихся чисел
        if u1 + u2 == 2: # сумма условий равна 2 (третье неучитывается, тк невозможно)
            c+=1
print(c)
